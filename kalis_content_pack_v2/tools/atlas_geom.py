W, H = 300, 760
MID = 150.0
SEP = 1.1  # demi-largeur de la séparation entre régions voisines


def catmull_closed(pts, n=8, tension=0.5):
    """Spline de Catmull-Rom fermée, échantillonnée (n points par segment)."""
    out = []
    m = len(pts)
    for i in range(m):
        p0, p1, p2, p3 = pts[(i - 1) % m], pts[i], pts[(i + 1) % m], pts[(i + 2) % m]
        for k in range(n):
            t = k / n
            t2, t3 = t * t, t * t * t
            x = tension * ((2 * p1[0]) + (-p0[0] + p2[0]) * t + (2 * p0[0] - 5 * p1[0] + 4 * p2[0] - p3[0]) * t2
                           + (-p0[0] + 3 * p1[0] - 3 * p2[0] + p3[0]) * t3)
            y = tension * ((2 * p1[1]) + (-p0[1] + p2[1]) * t + (2 * p0[1] - 5 * p1[1] + 4 * p2[1] - p3[1]) * t2
                           + (-p0[1] + 3 * p1[1] - 3 * p2[1] + p3[1]) * t3)
            out.append((x, y))
    return out


def mirror(pts):
    return [(2 * MID - x, y) for x, y in pts]


def mirror_pts_list(pts):
    return [(2 * MID - x, y) for x, y in pts]


