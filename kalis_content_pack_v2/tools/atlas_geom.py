"""Géométrie de l'atlas musculaire (L9R, étape 3) — dessin ORIGINAL de Claude.

Repère : viewBox 0 0 300 760 par vue (rapport proche de la carte actuelle de
l'application, 281 × 760). Chaque vue est décrite pour le côté DROIT du
personnage (x < 150 en vue de face ; en vue de dos le côté droit du personnage
est à droite de l'image, x > 150) puis symétrisée par x' = 300 − x.

Méthode : la silhouette et chaque région musculaire superficielle sont des
« blobs » (points de contrôle → spline de Catmull-Rom fermée). Les régions
sont ensuite découpées (bibliothèque shapely) : intersection avec la
silhouette, soustraction des régions déjà posées, puis léger retrait (`SEP`)
qui trace la séparation entre muscles voisins. Aucun chevauchement n'est donc
possible par construction ; les trous sont mesurés par `atlas_build.py`.

Toutes les coordonnées ont été posées et ajustées par contrôle visuel
(planches PNG rendues par Chromium), sans copie d'un tracé existant.
"""
